"""
convert_uatd.py
---------------
Convert the UATD dataset (PASCAL VOC XML + BMP) to YOLO detection format.

UATD layout (after unzipping each archive):
    UATD_Training/
        image/          *.bmp
        annotation/     *.xml   (matching stem)

Typical use (after downloading from figshare):
    python convert_uatd.py \\
        --train-root path/to/UATD_Training \\
        --val-root   path/to/UATD_Test_1 \\
        --out        data/uatd

Writes images + labels under out/, plus uatd.yaml ready for train.py --data uatd.yaml.
Class names are auto-discovered from XML <name> tags (sorted for stable ids).
"""
from __future__ import annotations

import argparse
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path

import cv2


def voc_box_to_yolo(xmin: float, ymin: float, xmax: float, ymax: float,
                    img_w: int, img_h: int) -> tuple[float, float, float, float]:
    """VOC pixel corners -> YOLO normalized cx cy w h."""
    w = max(xmin, xmax) - min(xmin, xmax)
    h = max(ymin, ymax) - min(ymin, ymax)
    cx = min(xmin, xmax) + w / 2
    cy = min(ymin, ymax) + h / 2
    return cx / img_w, cy / img_h, w / img_w, h / img_h


def parse_voc(path: Path) -> list[tuple[str, float, float, float, float]]:
    """Return [(class_name, xmin, ymin, xmax, ymax), ...]."""
    root = ET.parse(path).getroot()
    objs = []
    for obj in root.findall("object"):
        name = (obj.findtext("name") or "").strip()
        bb = obj.find("bndbox")
        if not name or bb is None:
            continue
        xmin = float(bb.findtext("xmin", "0"))
        ymin = float(bb.findtext("ymin", "0"))
        xmax = float(bb.findtext("xmax", "0"))
        ymax = float(bb.findtext("ymax", "0"))
        objs.append((name, xmin, ymin, xmax, ymax))
    return objs


def split_dirs(root: Path) -> tuple[Path, Path]:
    """Find image/ and annotation/ under root (case-insensitive)."""
    img_dir = ann_dir = None
    for p in root.iterdir():
        if not p.is_dir():
            continue
        low = p.name.lower()
        if low in ("image", "images"):
            img_dir = p
        elif low in ("annotation", "annotations"):
            ann_dir = p
    if img_dir is None or ann_dir is None:
        raise FileNotFoundError(
            f"Expected image/ and annotation/ under {root}; found: "
            f"{[x.name for x in root.iterdir() if x.is_dir()]}"
        )
    return img_dir, ann_dir


def discover_classes(ann_dirs: list[Path]) -> list[str]:
    names: set[str] = set()
    for d in ann_dirs:
        for xml in d.glob("*.xml"):
            for name, *_ in parse_voc(xml):
                names.add(name)
    return sorted(names)


def convert_one(img_path: Path, ann_path: Path, out_img: Path, out_lbl: Path,
                class_map: dict[str, int]) -> int:
    img = cv2.imread(str(img_path))
    if img is None:
        raise ValueError(f"could not read image: {img_path}")
    h, w = img.shape[:2]
    lines = []
    for name, xmin, ymin, xmax, ymax in parse_voc(ann_path):
        if name not in class_map:
            continue
        cid = class_map[name]
        cx, cy, bw, bh = voc_box_to_yolo(xmin, ymin, xmax, ymax, w, h)
        lines.append(f"{cid} {cx:.6f} {cy:.6f} {bw:.6f} {bh:.6f}")
    out_img.parent.mkdir(parents=True, exist_ok=True)
    out_lbl.parent.mkdir(parents=True, exist_ok=True)
    cv2.imwrite(str(out_img), img)
    out_lbl.write_text("\n".join(lines) + ("\n" if lines else ""), encoding="utf-8")
    return len(lines)


def convert_split(img_dir: Path, ann_dir: Path, out_images: Path, out_labels: Path,
                  class_map: dict[str, int]) -> tuple[int, int]:
    n_img = n_box = 0
    exts = {".bmp", ".jpg", ".jpeg", ".png"}
    for img_path in sorted(img_dir.iterdir()):
        if img_path.suffix.lower() not in exts:
            continue
        ann_path = ann_dir / (img_path.stem + ".xml")
        if not ann_path.exists():
            continue
        stem = img_path.stem
        out_img = out_images / f"{stem}.jpg"
        out_lbl = out_labels / f"{stem}.txt"
        n_box += convert_one(img_path, ann_path, out_img, out_lbl, class_map)
        n_img += 1
    return n_img, n_box


def write_yaml(out_root: Path, classes: list[str], yaml_path: Path | None = None) -> Path:
    """Write uatd.yaml with path relative to the yaml file's directory."""
    yaml_path = yaml_path or Path("uatd.yaml")
    try:
        rel = out_root.resolve().relative_to(yaml_path.resolve().parent)
        path_str = "./" + rel.as_posix()
    except ValueError:
        path_str = out_root.as_posix()
    lines = [
        "# UATD dataset — auto-generated by convert_uatd.py",
        f"path: {path_str}",
        "train: images/train",
        "val: images/val",
        "",
        "names:",
    ]
    for i, c in enumerate(classes):
        lines.append(f"  {i}: {c}")
    yaml_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return yaml_path


def run_self_test() -> None:
    """Synthetic VOC box sanity check (400x200, 200x100 centered box -> 0.5 0.5 0.5 0.5)."""
    cx, cy, bw, bh = voc_box_to_yolo(100, 50, 300, 150, 400, 200)
    assert abs(cx - 0.5) < 1e-6 and abs(cy - 0.5) < 1e-6
    assert abs(bw - 0.5) < 1e-6 and abs(bh - 0.5) < 1e-6

    import tempfile
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        img_dir, ann_dir = td / "image", td / "annotation"
        img_dir.mkdir()
        ann_dir.mkdir()
        cv2.imwrite(str(img_dir / "sample.bmp"), 255 * cv2.cvtColor(
            __import__("numpy").zeros((200, 400), dtype="uint8"), cv2.COLOR_GRAY2BGR))
        (ann_dir / "sample.xml").write_text("""<?xml version="1.0"?>
<annotation><size><width>400</width><height>200</height></size>
<object><name>cube</name><bndbox>
<xmin>100</xmin><ymin>50</ymin><xmax>300</xmax><ymax>150</ymax>
</bndbox></object></annotation>""", encoding="utf-8")
        out = td / "out"
        classes = discover_classes([ann_dir])
        assert classes == ["cube"]
        cmap = {c: i for i, c in enumerate(classes)}
        n, boxes = convert_split(img_dir, ann_dir, out / "images", out / "labels", cmap)
        assert n == 1 and boxes == 1
        line = (out / "labels" / "sample.txt").read_text().strip()
        assert line == "0 0.500000 0.500000 0.500000 0.500000", line
    print("self-test OK")


def main():
    ap = argparse.ArgumentParser(description="Convert UATD VOC XML -> YOLO format")
    ap.add_argument("--train-root", type=Path,
                    help="Unzipped UATD_Training folder (contains image/ + annotation/)")
    ap.add_argument("--val-root", type=Path,
                    help="Unzipped UATD_Test_1 (or Test_2) folder")
    ap.add_argument("--out", type=Path, default=Path("data/uatd"),
                    help="Output dataset root (creates images/train, labels/train, ...)")
    ap.add_argument("--self-test", action="store_true", help="Run built-in sanity checks and exit")
    args = ap.parse_args()

    if args.self_test:
        run_self_test()
        return

    if not args.train_root or not args.val_root:
        ap.error("--train-root and --val-root are required unless --self-test")
    train_img, train_ann = split_dirs(args.train_root)
    val_img, val_ann = split_dirs(args.val_root)
    classes = discover_classes([train_ann, val_ann])
    if not classes:
        raise SystemExit("No classes found in XML annotations.")
    class_map = {c: i for i, c in enumerate(classes)}
    print("Classes:", classes)

    out = args.out
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    tr_n, tr_b = convert_split(train_img, train_ann,
                               out / "images" / "train", out / "labels" / "train", class_map)
    va_n, va_b = convert_split(val_img, val_ann,
                               out / "images" / "val", out / "labels" / "val", class_map)
    yaml_path = write_yaml(out, classes)
    print(f"  train: {tr_n} images, {tr_b} boxes -> {out / 'images' / 'train'}")
    print(f"  val:   {va_n} images, {va_b} boxes -> {out / 'images' / 'val'}")
    print(f"  wrote {yaml_path}")


if __name__ == "__main__":
    main()
